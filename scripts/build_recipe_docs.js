// scripts/build_recipe_docs.js — regenerate docs/recipe-pack.md from data/recipe_pack.json
//
// The recipe table is generated so provenance (repo + licence) can never drift from
// the records the site actually ships.
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const pack = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'recipe_pack.json'), 'utf8'));
const STYLE_LABEL = {
  teardown: 'annotated teardown', hero: 'first-fold mock', tokens: 'token sheet', materials: 'surface ladder',
  timeline: 'tween timeline', bezier: 'easing curves', timing: 'stagger + duration ruler', matrix: 'transform decomposition',
  scrollmap: 'pinned progress map', stack: 'sticky stack', pointer: 'pointer mechanics', scene: '3D scene',
  svgdraw: 'path / Lottie draw', reveal: 'text reveal', states: 'state machine', responsive: 'breakpoint trio',
  report: 'acceptance report', diff: 'masked pixel diff', micro: 'micro-interaction strip', phases: 'timed playbook',
  filmstrip: 'capture filmstrip', marquee: 'infinite marquee', textfx: 'kinetic / decrypt text', shader: 'shader field',
  transition: 'curtain / view transition', bento: 'bento grid', gallery: 'horizontal gallery', tilt: 'cursor tilt card',
  trail: 'velocity trail',
};
const PACK_TITLE = {
  rea: ['Reverse-engineering (morluto/rea)', 'Extract the real motion values from a live site, then rebuild them.'],
  craft: ['Craft pipeline (storytold/craft-anything)', 'Blueprint → tokens → mechanics → build → measured self-test.'],
  community: ['Community effect recipes', 'Open pattern provenance from MIT-licensed component libraries and web standards.'],
};
const rows = pack.map((r) => [
  '`' + r.id + '`',
  r.title,
  (PACK_TITLE[r.source.pack] || ['?'])[0].split(' (')[0],
  r.source.repo === 'community sources' ? r.source.research.replace(/\|/g, '/') : r.source.repo,
  r.source.license,
  String(r.prompt.trim().split(/\s+/).length),
]);
const lines = [];
lines.push('# Recipe pack — UI replication prompts');
lines.push('');
lines.push('44 prompts that turn "make it look like that site" into a measured workflow: capture the reference,');
lines.push('extract the real values, rebuild it in a known stack, and prove the result with a self-test.');
lines.push('');
lines.push('Rows are generated by `node scripts/build_recipe_docs.js` from `data/recipe_pack.json`, which is also');
lines.push('the source the catalog build reads. Preview media is generated by');
lines.push('`python scripts/render_recipe_previews.py --all` from the pure-CSS demos in `scripts/recipe_demo.*`.');
lines.push('');
for (const [packKey, [title, blurb]] of Object.entries(PACK_TITLE)) {
  const entries = pack.filter((r) => r.source.pack === packKey);
  lines.push('## ' + title + ' — ' + entries.length + ' prompts');
  lines.push('');
  lines.push(blurb);
  lines.push('');
  lines.push('| id | prompt | visual | provenance | licence | words |');
  lines.push('| --- | --- | --- | --- | --- | ---: |');
  for (const r of entries) {
    lines.push('| `' + r.id + '` | ' + r.title + ' | ' + (STYLE_LABEL[r.demo.style] || r.demo.style) + ' | ' + r.source.repo.replace(/\|/g, '/') + ' | ' + r.source.license + ' | ' + r.prompt.trim().split(/\s+/).length + ' |');
  }
  lines.push('');
}
lines.push('## Provenance and licence notes');
lines.push('');
lines.push('- Prompt bodies are original syntheses written for this catalog. They are attributed to the repository or');
lines.push('  library whose method or pattern they encode; no upstream prose or shader source is copied verbatim.');
lines.push('- `morluto/rea` is MIT licensed. `storytold/craft-anything` is Apache-2.0.');
lines.push('- Community rows cite the MIT-licensed library or web standard they follow. React Bits is MIT **plus the');
lines.push('  Commons Clause**: its components may be used in apps with attribution, but not resold or redistributed as');
lines.push('  components — the prompts below only describe the pattern, never ship library code.');
lines.push('- Demo media is rendered from original CSS compositions in this repository (MIT), not from upstream sites.');
lines.push('');
lines.push('## Add a recipe');
lines.push('');
lines.push('1. Append a record to `data/recipe_pack.json` with the fields used above (id, title, description, type, tags,');
lines.push('   palette, prompt, notes, demo, source, sort_order). Use a negative `sort_order` to pin a pack card above the');
lines.push('   scraped catalog.');
lines.push('2. `python scripts/render_recipe_previews.py --ids <id>` to render `assets/previews/<id>.{mp4,webp}`.');
lines.push('3. `node scripts/build.js && node scripts/build_recipe_docs.js`.');
lines.push('4. `node --test scripts/tests/recipe-pack.test.js`.');
lines.push('');

fs.writeFileSync(path.join(ROOT, 'docs', 'recipe-pack.md'), lines.join('\n'), 'utf8');
console.log('wrote docs/recipe-pack.md  rows=' + pack.length);
